// Spawns returns every place the world puts mobs, in world coordinates, as many in each
// pack as its map's Mobs says.
func Spawns() []Spawn {
	return spawnsOn(maps)
}

// spawnsOn is every place the maps put mobs, each pack's count multiplied by its map's
// Mobs.
func spawnsOn(maps []Map) []Spawn {
	var all []Spawn
	for _, m := range maps {
		for _, s := range spawnsByMap[m.Name] {
			if s.family != "" {
				all = append(all, packOf(m, s))
				continue
			}
			count := max(s.count, 1)
			if count > 1 {
				count = max(1, int(math.Round(float64(count)*m.Mobs)))
			}
			var spots []Spot
			for _, p := range s.spots {
				spots = append(spots, Spot{m.X + p.X, m.Y + p.Y})
			}
			all = append(all, Spawn{VNum: s.vnum, X: m.X + s.x, Y: m.Y + s.y, Spread: s.spread, Count: count, Spots: spots,
				Respawn: time.Duration(s.respawn) * time.Second, Facing: s.facing})
		}
	}
	return all
}

// packOf is a family's pack on the map: its kinds and their weights and how soon it comes
// back, from how far out from the village it stands, and how many it holds, multiplied by
// the map's Mobs.
func packOf(m Map, s spawnAt) Spawn {
	d := float64(s.out)
	least := max(1, int(math.Round(smallest*m.Mobs)))
	return Spawn{Kinds: kindsAt(s.family, d), MinCount: least, Count: max(least, int(math.Round(largest*m.Mobs))),
		X: m.X + s.x, Y: m.Y + s.y, Spread: s.spread, Respawn: time.Duration(backAfter(d)) * time.Second}
}
