// Spawn is a place where the world puts mobs: Count of the kind VNum, each at a random
// point within Spread of X, Y, or, for a stone, at one of its Spots picked afresh each
// time it comes back. A pack of a family has Kinds instead: each time it comes back it
// holds MinCount to Count of them, each kind as likely as its weight.
type Spawn struct {
	VNum     uint16
	Kinds    []Kind
	MinCount int
	X, Y     int32 // world coordinates
	Spread   int32
	Count    int
	Spots    []Spot
	Respawn  time.Duration // how long after its death each comes back; none for its kind's own
	Facing   float32       // degrees, as ADD sends them: where an NPC that never moves looks
}

// Spot is a point in world coordinates.
type Spot struct{ X, Y int32 }

// spawnAt is a spawn written in the map's own coordinates, as the client's map files and
// the minimap give them.
type spawnAt struct {
	vnum    uint16
	x, y    int32
	spread  int32
	count   int
	respawn int    // seconds
	spots   []Spot // in the map's coordinates
	facing  float32
	family  family // a pack of the family's kinds, as many as its distance out says
	out     int32  // how far its centre lies from the village: its NPCs and the safe ground about them
}

